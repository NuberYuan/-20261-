# Step6: 项目整合与代码生成准备
#
# 将 Step4（需求分析）和 Step5（工程设计）横向对齐，规则驱动地生成
# 代码生成 Agent 可直接消费的项目简报。
#
# 流程:
#   Step4 YAML + Step5 YAML → 一致性检查 → 冲突/缺失/假设 → project_brief.yaml
#
# 核心产出:
#   project_brief.yaml —— 项目元信息 + 一致性报告 + 需求摘要 + 设计摘要
#                         + 追溯矩阵 + 代码生成计划 + 风险与注意事项
#
# 特点:
#   - 纯规则驱动（不调用 LLM）。一致性是确定性事实比对，整合是确定性搬运与映射
#   - step6_consistency.py: 一致性检查器（冲突/缺失/假设识别）
#   - step6_summarizer.py:  项目整合器（需求/设计摘要、追溯矩阵、代码生成计划）
